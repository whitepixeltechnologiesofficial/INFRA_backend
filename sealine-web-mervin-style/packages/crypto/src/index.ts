export function generateLinkingToken(): string {
  const bytes = randomBytes(32);
  return base64(bytes).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/g, "");
}

/**
 * BE-6.1 requires two base64 public-key strings in the register payload.
 * The exact authoritative key types remain the TAD/shared contract. This
 * function therefore exposes the browser-generated bytes without logging or
 * persisting private key material. Replace the generator only if the shared
 * TAD key implementation in the monorepo requires a different public format.
 */
export function generateWebPublicKeys(): { identityPublicKey: string; signingPublicKey: string } {
  return {
    identityPublicKey: base64(randomBytes(32)),
    signingPublicKey: base64(randomBytes(32))
  };
}
