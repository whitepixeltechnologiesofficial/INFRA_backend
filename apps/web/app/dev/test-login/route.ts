function devError(status: number, title: string, detail: string): NextResponse {
  return new NextResponse(devPage({ title, detail, ok: false }), {
    status,
    headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-store" },
  });
}

export async function GET(req: NextRequest): Promise<NextResponse> {
  // 1. Development only. This is the server-side gate — in a production build
  //    the route exists but answers 404 and never reaches the protocol.
  if (!devTestLoginAllowed(process.env.NODE_ENV)) {
    return devError(404, "Not found", "This route is only available while the app runs in development mode.");
  }
  if (!isBackendConfigured()) {
    return devError(503, "Linking service not configured", "Set <code>API_BASE_URL</code> to the backend origin and try again.");
  }

  // 2. The test phone. An unlisted number is refused, never mapped to a default.
  //    Which account it is is NOT decided here — this module knows no userId and
  //    no display name, and sends only the number below.
  const phone = normalizeDevPhone(req.nextUrl.searchParams.get("phone"));
  const entry = devTestPhone(phone);
  if (!entry) {
    const allowed = devTestPhoneList().map((p) => `<code>${escapeHtml(p)}</code>`).join(", ");
    return devError(400, "Unsupported test phone", `This route only signs in test accounts. Allowed: ${allowed}.`);
  }

  // 3. Register a link exactly as the browser does, with the one CSPRNG token
  //    module and the same public identity bundle shape.
    const token = generateWebLinkToken();
  const registered = await webLinkApi().register({ token, identity: devIdentityBundle() });
  if (registered.ok !== true) {
    console.error("[dev/test-login] registration failed:", registered.error);
    return devError(502, "Could not start a link", "The backend refused to register this test login.");
  }

  // 4. Stand in for the physical scan using the backend's own dev trigger. It
  //    performs the real `approve` — the same atomic claim, the same minting —
  //    and hands the single-use code back inline, because this route has no
  //    browser socket in the room to be pushed to.
  //
  //    `phoneNumber` is the ONLY identity input. The backend resolves it against
  //    its real user store, so the session is issued for an account that exists
  //    rather than for one this frontend asserted.
  const scan = await webLinkApi().dev.simulateScan({
    token,
    phoneNumber: entry.e164,
    mobileDeviceId: DEV_TEST_DEVICE_ID,
    deliverInline: true,
  });
  if (scan.ok !== true) {
    console.error("[dev/test-login] scan trigger failed:", scan.error);
    // The backend's own message is the useful one here: an unknown number is
    // refused by name, with the fix, rather than a generic failure.
    const detail = scan.message?.trim();
    return devError(
      502,
      "Could not approve the link",
      detail && detail.length > 0 ? escapeHtml(detail) : "The backend's development scan trigger was refused.",
    );
  }
  if (!scan.code) {
    return devError(502, "Could not approve the link", "The backend approved the link but returned no redemption code.");
  }

  // 5. Spend it through the normal redeem, which is what actually mints the
  //    session (and enforces one browser).
  const redeemed = await webLinkApi().redeemLink(scan.code);
  if (redeemed.ok !== true) {
    console.error("[dev/test-login] redeem failed:", redeemed.error);
    return devError(502, "Could not complete the login", "The redemption code could not be redeemed.");
  }
  if (!redeemed.userId) {
    return devError(500, "No session identity", "The backend issued a session without an account.");
  }

  // 6. The same HttpOnly cookie the QR flow sets. Boot authentication reads this
  //    cookie and nothing else, so the app opens exactly as it would after a
  //    real scan — no client change, no stored credential.
  //
  //    Who was signed in comes from that session (the account the backend
  //    resolved), never from anything on this page.
  const displayName = redeemed.accountName?.trim() || entry.e164;
  return new NextResponse(
    devPage({
      title: `Signed in as ${escapeHtml(displayName)}`,
      detail: `Local test session for <code>${escapeHtml(entry.label)}</code> is active. Opening Sealine Web…`,
      ok: true,
      autoRedirect: true,
    }),
    {
      status: 200,
      headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-store", "Set-Cookie": setSessionCookie(redeemed.sessionToken) },
    },
  );
}
