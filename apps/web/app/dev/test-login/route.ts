// GET /dev/test-login?phone=9876543210 — LOCAL DEVELOPMENT ONLY.
//
// A developer convenience for opening the EXISTING Web client as a known test
// account without holding a physical phone in front of a QR every time. It is
// deliberately NOT a second login path and NOT a mock: it runs the real linking
// protocol end to end through the existing seams and finishes with the same
// HttpOnly web session the QR flow produces.
//
//   validate development mode -> refuses to authenticate in production (404)
//   validate the test phone   -> an explicit allowlist, never a default account
//   register a link           -> webLinkApi().register, the same seam /api/link/register uses
//   stand in for the scan     -> the backend's own dev-only trigger, service.approve,
//                                which resolves the phone to an account in the
//                                real user store (this route names no userId)
//   spend the minted code     -> the same single-use redeem the browser performs
//   set the HttpOnly cookie   -> the same cookie, so boot auth is completely unchanged
//   redirect to /             -> the normal authenticated Web UI
//
// WHY THERE IS NO SOCKET HERE. The previous version dialled the realtime link
// channel purely so it could sit in `link:<hash(token)>` and be handed the
// pushed code — which made it fail with "the realtime link channel did not come
// up" whenever that extra hop could not be dialled, for reasons that have
// nothing to do with whether the flow works. A physical scan does not need a
// browser socket either: the phone pushes to the room, and this route is not a
// browser. So the trigger is asked for the code inline instead, over the same
// server-to-server hop the redeem already uses. Nothing about the realtime
// stack is weakened to get here — no handshake, ticket, room or push code is
// touched, and
// the browser-side push path in web-link-client.ts is completely unchanged.
//
// No control is bypassed to get there. The token is still generated by the one
// CSPRNG token module, the code is still minted by the backend's atomic
// `approve`, the session is still minted by the backend's atomic `redeem` (so the
// one-browser rule still runs), and the credential still only ever lands in an
// HttpOnly cookie — never in a URL, never in a response body, never in storage.
//
// The single thing replaced is the physical act of scanning the QR, which is
// exactly what the backend's existing `_dev/scan` trigger (dev-only, not mounted
// in production) exists to simulate.
//
// Nothing in the shipped app imports this file, and app/wpt/qr-gate.tsx only
// offers a code for it in a development build.

import { NextResponse, type NextRequest } from "next/server";
import { generateIdentityKeyPair } from "@wpt/crypto";
import type { WebLinkIdentityBundle } from "@wpt/shared";
import {
  DEV_TEST_DEVICE_ID,
  devTestLoginAllowed,
  devTestPhone,
  devTestPhoneList,
  normalizeDevPhone,
} from "../../lib/dev-test-login";
import { generateWebLinkToken } from "../../lib/web-link-token";
import { isBackendConfigured, setSessionCookie, webLinkApi } from "../../lib/web-link-server";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

function escapeHtml(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function toBase64Url(bytes: Uint8Array): string {
  return Buffer.from(bytes).toString("base64url");
}

/**
 * A fresh, throwaway ed25519 PUBLIC bundle, built exactly as the browser builds
 * one, so the registered link has a real key rather than a placeholder.
 *
 * It is built from @wpt/crypto directly rather than by importing the browser
 * half: this file is server code, and the browser half drags in the realtime
 * client. That keeps the realtime client out of this module's graph entirely
 * instead of merely not calling it, so the "no socket here" claim is structural. The PRIVATE
 * key is discarded immediately and never leaves this function's scope - it is
 * not stored, not returned, not logged, and not sent anywhere. This is a
 * development link that only ever authenticates an allowlisted test phone.
 */
function devIdentityBundle(): WebLinkIdentityBundle {
  const pair = generateIdentityKeyPair();
  return { version: 1, publicKey: toBase64Url(pair.publicKey), createdAt: new Date().toISOString() };
}

