// lib/sha256.ts
//
// Pure-JS SHA-256 (FIPS 180-4) returning a lowercase hex digest.
//
// The mobile app ships no crypto dependency today (no expo-crypto, no
// @noble/hashes in its dependency tree), and adding one requires a network
// install. This self-contained, dependency-free implementation exists so the
// contact-matching hashing (DB-2.3, Tech Arch §14.1–14.2) can run on-device
// without one — SHA-256 is standardized/fully specified, so there is no
// protocol risk in implementing it directly. Verified against the NIST test
// vectors at build time (see the unit-check harness).
//
// Input is treated as UTF-8 text.

