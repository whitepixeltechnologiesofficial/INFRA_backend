-- ============================================================
-- 012_rename_message_relay_to_pending_messages.sql
-- Run this in: Supabase → SQL Editor → New Query → Run
--
-- Renames public.message_relay to public.pending_messages to match
-- the Tech Arch S6.4 name already referenced by 009. Existing rows
-- survive: this migration uses RENAME only — no DROP TABLE, no
-- CREATE TABLE, no DROP FUNCTION (the cleanup body is refreshed in
-- place with CREATE OR REPLACE FUNCTION).
--
-- IMPORTANT: PostgreSQL does NOT rename indexes, constraints or
-- triggers when a table is renamed, so each is renamed explicitly:
--   ALTER TABLE ... RENAME CONSTRAINT
--   ALTER INDEX  ... RENAME
--   ALTER TRIGGER ... RENAME
-- Functions are renamed with ALTER FUNCTION ... RENAME TO. A trigger
-- follows its function dependency automatically, so no ALTER TRIGGER
-- ... EXECUTE FUNCTION repoint is required.
--
-- Objects renamed (exact names from 004, 004b, 006, 008, 009, 011):
--   6 indexes    idx_message_relay_recipient_user,
--                idx_message_relay_recipient_device,
--                idx_message_relay_recipient_group,
--                idx_message_relay_expires,
--                idx_message_relay_created,
--                idx_message_relay_voice_group
--   1 primary key
--                message_relay_pkey (auto-generated by the inline
--                `id uuid PRIMARY KEY` in 004)
--   3 CHECK      message_relay_recipient_exactly_one,
--                message_relay_size_bytes_non_negative,
--                message_relay_message_type_check
--   5 FK         message_relay_reply_to_fkey,
--                message_relay_sender_device_id_devices_id_fk,
--                message_relay_recipient_device_id_devices_id_fk,
--                message_relay_recipient_user_id_users_id_fk,
--                message_relay_recipient_group_id_groups_id_fk
--   1 trigger    trg_message_relay_purge_storage
--   2 functions  cleanup_message_relay(), tg_message_relay_purge_storage()
--   1 cron job   cleanup-message-relay
--
-- NOTE: message_relay_one_recipient_check was DROPPED by 011 and no
--       longer exists in a migrated database; it is intentionally
--       not renamed here.
-- ============================================================

BEGIN;

-- 1. Rename the table (rows preserved)
ALTER TABLE public.message_relay RENAME TO pending_messages;

-- 2. Primary key: auto-named message_relay_pkey by `id uuid PRIMARY KEY`
--    in 004. Renamed explicitly because table rename does not cascade.
ALTER TABLE public.pending_messages
    RENAME CONSTRAINT message_relay_pkey TO pending_messages_pkey;

-- 3. CHECK constraints (3)
ALTER TABLE public.pending_messages
    RENAME CONSTRAINT message_relay_recipient_exactly_one
    TO pending_messages_recipient_exactly_one;

ALTER TABLE public.pending_messages
    RENAME CONSTRAINT message_relay_size_bytes_non_negative
    TO pending_messages_size_bytes_non_negative;

ALTER TABLE public.pending_messages
    RENAME CONSTRAINT message_relay_message_type_check
    TO pending_messages_message_type_check;

-- 4. Foreign key constraints (5)
ALTER TABLE public.pending_messages
    RENAME CONSTRAINT message_relay_reply_to_fkey
    TO pending_messages_reply_to_fkey;

ALTER TABLE public.pending_messages
    RENAME CONSTRAINT message_relay_sender_device_id_devices_id_fk
    TO pending_messages_sender_device_id_devices_id_fk;

ALTER TABLE public.pending_messages
    RENAME CONSTRAINT message_relay_recipient_device_id_devices_id_fk
    TO pending_messages_recipient_device_id_devices_id_fk;

ALTER TABLE public.pending_messages
    RENAME CONSTRAINT message_relay_recipient_user_id_users_id_fk
    TO pending_messages_recipient_user_id_users_id_fk;

ALTER TABLE public.pending_messages
    RENAME CONSTRAINT message_relay_recipient_group_id_groups_id_fk
    TO pending_messages_recipient_group_id_groups_id_fk;

-- 5. Indexes (6; see names in header)
ALTER INDEX public.idx_message_relay_recipient_user
    RENAME TO idx_pending_messages_recipient_user;
ALTER INDEX public.idx_message_relay_recipient_device
    RENAME TO idx_pending_messages_recipient_device;
ALTER INDEX public.idx_message_relay_recipient_group
    RENAME TO idx_pending_messages_recipient_group;
ALTER INDEX public.idx_message_relay_expires
    RENAME TO idx_pending_messages_expires;
ALTER INDEX public.idx_message_relay_created
    RENAME TO idx_pending_messages_created;
ALTER INDEX public.idx_message_relay_voice_group
    RENAME TO idx_pending_messages_voice_group;

-- 6. Trigger: rename now. Its function dependency is renamed in step 8
--    and follows this trigger automatically — no EXECUTE FUNCTION needed.
ALTER TRIGGER trg_message_relay_purge_storage ON public.pending_messages
    RENAME TO trg_pending_messages_purge_storage;

-- 7. Rename the cleanup function, then refresh its body so it references
--    pending_messages (the pre-rename body pointed at message_relay, which
--    no longer exists after step 1)
ALTER FUNCTION public.cleanup_message_relay()
    RENAME TO cleanup_pending_messages;

CREATE OR REPLACE FUNCTION public.cleanup_pending_messages()
RETURNS void
LANGUAGE sql
AS $$ DELETE FROM public.pending_messages
     WHERE delivered_at IS NOT NULL OR expires_at < now(); $$;

-- 8. Rename the storage-purge trigger function. Its body (from 009) only
--    touches storage.objects, so no body change is required. The trigger
--    renamed in step 6 follows this rename automatically through its
--    function dependency — no ALTER TRIGGER ... EXECUTE FUNCTION needed.
ALTER FUNCTION public.tg_message_relay_purge_storage()
    RENAME TO tg_pending_messages_purge_storage;

-- 9. Cron: replace the old job with the new one. Same schedule and
--    command shape as 004:81-85, calling the new function. The
--    unschedule is guarded so the migration still succeeds if the
--    old job (or the cron schema) is absent.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'cleanup-message-relay')
    THEN
        PERFORM cron.unschedule('cleanup-message-relay');
    END IF;
END
$$;

SELECT cron.schedule(
    'cleanup-pending-messages',
    '*/5 * * * *',
    $$ SELECT public.cleanup_pending_messages(); $$
);

-- 10. Replace the COMMENT ON TABLE from 009:72 for the renamed table
COMMENT ON TABLE public.pending_messages IS
    'Message queue per recipient device. Tech Arch S6.4 name (pending_messages). Deleting a row also removes its media_path object from Storage (S11.4).';

COMMIT;

